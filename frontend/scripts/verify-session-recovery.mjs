import {chromium} from "playwright";
import assert from "node:assert/strict";
const base=process.env.BASE_URL||"http://localhost:3000";
const browser=await chromium.launch({args:["--no-sandbox","--enable-gpu","--use-gl=angle","--use-angle=gl"]});
const key="autolink.vehicle-session.v1.bmw-m2";
try{
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  const errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  page.on("console",m=>{if(/hydrat|server rendered HTML/i.test(m.text()))errors.push(m.text());});
  const saved=()=>page.evaluate(key=>JSON.parse(localStorage.getItem(key)),key);
  const agent=page.getByRole("region",{name:"Vehicle Safety Agent",exact:true});
  const openSimulator=async()=>{if(!await agent.locator('.agent-simulator').evaluate(el=>el.open))await agent.locator('.agent-simulator summary').click();};
  const reload=async()=>{await page.reload();await page.locator('.session-notice').filter({hasText:'Đã khôi phục'}).waitFor();};
  await page.goto(base);
  await page.getByRole('button',{name:'Inject Overheating',exact:true}).click();
  await page.getByRole('button',{name:'Tôi đang giảm tốc',exact:true}).click();
  await openSimulator();await page.getByRole('button',{name:'Mô phỏng xe giảm tốc',exact:true}).click();
  const before=await saved();
  await reload();
  await page.getByRole('button',{name:'Xác nhận hướng dẫn dừng (demo)',exact:true}).waitFor();
  const after=await saved();
  assert.equal(after.incident.id,before.incident.id);
  assert.deepEqual(after.incident.action,before.incident.action);
  assert.deepEqual(after.incident.timeline,before.incident.timeline);
  assert.equal(after.history.length,before.history.length);
  assert.equal(after.incident.driverAcknowledged,true);
  await page.getByRole('button',{name:'Chưa đồng ý',exact:true}).click();
  await reload();await page.getByRole('button',{name:'Xem lại đề xuất',exact:true}).waitFor();
  await page.getByRole('button',{name:'Xem lại đề xuất',exact:true}).click();
  // Click and start reload in the same task, before the delayed mock can complete.
  await page.getByRole('button',{name:'Xác nhận hướng dẫn dừng (demo)',exact:true}).evaluate(el=>el.click());
  assert.equal((await saved()).incident.action.status,'pending');
  await reload();
  await page.getByRole('button',{name:'Thử lại yêu cầu đã xác nhận',exact:true}).waitFor();
  await page.waitForTimeout(1700);
  assert.equal((await saved()).incident.action.status,'failed','reload must not resend');
  assert.deepEqual((await saved()).incident.action.payload,before.incident.action.payload);
  await page.getByRole('button',{name:'Thử lại yêu cầu đã xác nhận',exact:true}).click();
  await agent.getByText('Hướng dẫn demo đã sẵn sàng',{exact:true}).waitFor();
  await openSimulator();await page.getByRole('button',{name:'Mô phỏng xe đã dừng',exact:true}).click();
  const rescue=await saved();
  await reload();
  await page.getByRole('button',{name:'Xác nhận cứu hộ & chia sẻ (demo)',exact:true}).waitFor();
  assert.equal((await saved()).telemetry.rpm,0);
  assert.deepEqual((await saved()).incident.action,rescue.incident.action);
  await page.getByRole('button',{name:'Xác nhận cứu hộ & chia sẻ (demo)',exact:true}).click();
  await agent.getByText('Cứu hộ demo đã xác nhận',{exact:true}).waitFor();
  const completed=await saved();await reload();
  await agent.getByText('Cứu hộ demo đã xác nhận',{exact:true}).waitFor();
  assert.deepEqual((await saved()).incident.action,completed.incident.action);
  assert.deepEqual((await saved()).incident.timeline,completed.incident.timeline);
  await page.screenshot({path:'docs/screenshots/agent-session-restored.png',fullPage:true});
  await openSimulator();await page.getByRole('button',{name:'Mô phỏng chuỗi hạ nhiệt',exact:true}).click();
  await page.getByTestId('incident-status').filter({hasText:'Đã kết thúc sự cố'}).waitFor({timeout:15000});
  const resolved=await saved();await reload();
  await page.getByTestId('incident-status').filter({hasText:'Đã kết thúc sự cố'}).waitFor();
  assert.deepEqual((await saved()).incident.timeline,resolved.incident.timeline);
  await page.getByLabel('Kịch bản mô phỏng').selectOption('offline');
  const offline=await saved();await reload();
  assert.equal((await saved()).telemetry.connected,false);
  assert.equal((await saved()).telemetry.capturedAt,offline.telemetry.capturedAt);
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(600);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.evaluate(key=>localStorage.setItem(key,'{broken'),key);
  await page.reload();await page.getByRole('alert').filter({hasText:'Không đọc được phiên'}).waitFor();
  assert.equal(await page.evaluate(key=>localStorage.getItem(key),key),'{broken');
  assert.deepEqual(errors,[]);
  console.log('PASS: consent, decline, interrupted action/manual retry, stopped vehicle, successful rescue, resolved timeline, offline timestamp, mobile, corrupt storage and hydration across reloads.');
}finally{await browser.close();}
