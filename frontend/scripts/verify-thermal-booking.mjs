import {chromium} from "playwright";
import assert from "node:assert/strict";
const browser=await chromium.launch({args:["--no-sandbox","--enable-gpu","--use-gl=angle","--use-angle=gl"]});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(/hydrat|server rendered HTML/i.test(m.text()))errors.push(m.text());});
 await page.goto(process.env.BASE_URL||'http://localhost:3000');
 await page.waitForSelector('canvas[data-loaded="true"]',{timeout:60000});
 assert.equal(await page.locator('.metric-card.danger').count(),0);
 await page.getByLabel('Kịch bản mô phỏng').selectOption('environment');
 await page.locator('.metric-card.watch').first().waitFor();
 assert.equal(await page.locator('.metric-card.danger').count(),0);
 assert.equal(await page.locator('.engine-marker.heat-danger').count(),0);
 await page.getByRole('button',{name:'Inject Overheating',exact:true}).click();
 await page.locator('.viewer.thermal-danger').waitFor();
 assert.equal(await page.locator('.engine-marker.heat-danger').count(),2);
 assert.equal(await page.locator('.metric-card.danger').count(),2);
 assert.equal(await page.locator('.health-overview.critical').count(),1);
 assert.equal(await page.locator('.metric-card.danger').filter({hasText:'Điện áp'}).count(),0);
 await page.screenshot({path:'docs/screenshots/thermal-alert-dashboard.png',fullPage:true});
 await page.getByRole('button',{name:'Đặt lịch kiểm tra',exact:true}).click();
 assert.equal(await page.locator('#service-planner').evaluate(el=>el===document.activeElement),true);
 await page.getByRole('button',{name:'Xem garage đề xuất',exact:true}).click();
 await page.locator('.garage-option').filter({hasText:'Cooling Lab'}).click();
 await page.getByRole('button',{name:'Chọn thời gian',exact:true}).click();
 const date=await page.getByLabel('Ngày kiểm tra',{exact:true}).getAttribute('min');
 await page.getByLabel('Ngày kiểm tra',{exact:true}).fill(date);
 await page.getByLabel('Giờ hẹn',{exact:true}).selectOption('09:00');
 await page.getByRole('button',{name:'Kiểm tra lịch hẹn',exact:true}).click();
 const confirm=page.getByRole('button',{name:'Xác nhận lưu lịch demo',exact:true});
 const consent=page.getByLabel('Tôi đồng ý lưu lịch demo cho xe, garage và thời gian ở trên.');
 assert.equal(await confirm.isDisabled(),true);
 assert.equal(await page.evaluate(()=>localStorage.getItem('autolink.service-bookings.v1')),null);
 await consent.check();await page.getByRole('button',{name:'Sửa thông tin',exact:true}).click();
 await page.getByLabel('Giờ hẹn',{exact:true}).selectOption('11:00');
 await page.getByRole('button',{name:'Kiểm tra lịch hẹn',exact:true}).click();
 assert.equal(await consent.isChecked(),false);assert.equal(await confirm.isDisabled(),true);
 const approved=await page.locator('.booking-review dl').innerText();
 const incident=JSON.parse(await page.evaluate(()=>localStorage.getItem('autolink.vehicle-session.v1.bmw-m2'))).incident;
 const agent=page.getByRole('region',{name:'Vehicle Safety Agent',exact:true});
 if(!await agent.locator('.agent-simulator').evaluate(el=>el.open))await agent.locator('.agent-simulator summary').click();
 await page.getByRole('button',{name:'Mô phỏng xe đã dừng',exact:true}).click();
 await page.getByRole('button',{name:'Xác nhận cứu hộ & chia sẻ (demo)',exact:true}).waitFor();
 assert.equal(await page.locator('.booking-review dl').innerText(),approved,'telemetry changes cannot replace the reviewed snapshot');
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(600);
 await page.locator('.booking-review').scrollIntoViewIfNeeded();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'docs/screenshots/booking-confirm-mobile.png',fullPage:true});
 await consent.check();await confirm.click();
 await page.getByRole('heading',{name:'Đã lưu lịch hẹn demo',exact:true}).waitFor();
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('autolink.service-bookings.v1')));
 assert.equal(saved.length,1);assert.equal(saved[0].time,'11:00');assert.equal(saved[0].vehicleId,'bmw-m2');assert.equal(saved[0].reportId,incident.id);
 assert(approved.includes(saved[0].issue));
 await page.reload();await page.locator('.saved-booking.saved').waitFor();
 await page.getByLabel('Kịch bản mô phỏng').selectOption('offline');
 assert.equal(await page.locator('.metric-card.danger').count(),0);
 assert.equal(await page.locator('.engine-marker.heat-danger').count(),0);
 assert.equal(await page.locator('.viewer.thermal-danger').count(),0);
 assert.equal(await page.getByRole('button',{name:'Xem garage đề xuất',exact:true}).count(),0);
 await page.getByRole('button',{name:'Hủy lịch demo',exact:true}).click();
 await page.locator('.saved-booking.cancelled').waitFor();
 assert.deepEqual(errors,[]);
 console.log('PASS: localized thermal red/amber/normal/offline states, visible incident booking, three steps, explicit consent, edit resets consent, frozen review across escalation, persistence/cancellation and mobile.');
}finally{await browser.close();}
